function buildPlayer(
  line: Player['line'],
  [id, name, country, countryCode, subPosition, tier]: readonly [string, string, string, string, string, Tier],
): Player {
  return {
    id: `${countryCode.toLowerCase()}-${id}`,
    name,
    country,
    countryCode,
    photo: `/players/${countryCode.toLowerCase()}-${id}.jpg`,
    line,
    subPosition,
    tier,
    basePrice: pricingTable[line][tier],
  };
}
